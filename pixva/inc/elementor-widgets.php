if ( ! class_exists( 'Pixva_All_Tools_Widget' ) ) {
	/**
	 * ویجت جامع «۶۰ در ۱» برای ساخت سریع صفحه ابزارها.
	 */
	class Pixva_All_Tools_Widget extends \Elementor\Widget_Base {

		/**
		 * نام ویجت.
		 *
		 * @return string
		 */
		public function get_name() {
			return 'pixva_interactive_tool';
		}

		/**
		 * عنوان ویجت.
		 *
		 * @return string
		 */
		public function get_title() {
			return esc_html__( 'ابزار تعاملی پیکسوا (۶۰ در ۱)', 'pixva' );
		}

		/**
		 * آیکون.
		 *
		 * @return string
		 */
		public function get_icon() {
			return 'eicon-tools';
		}

		/**
		 * دسته‌بندی.
		 *
		 * @return array
		 */
		public function get_categories() {
			return array( 'pixva-diagnostics' );
		}

		/**
		 * کلیدواژه‌ها.
		 *
		 * @return array
		 */
		public function get_keywords() {
			return array( 'pixva', 'tool', 'ai', 'diagnostics', 'ابزار پیکسوا' );
		}

		/**
		 * کنترل‌ها.
		 *
		 * @return void
		 */
		protected function register_controls() {
			$this->start_controls_section(
				'pixva_all_content',
				array(
					'label' => esc_html__( 'تنظیمات ابزار', 'pixva' ),
					'tab'   => \Elementor\Controls_Manager::TAB_CONTENT,
				)
			);

			$options = array();
			foreach ( pixva_tools_registry() as $tool_id => $tool ) {
				$options[ (string) $tool_id ] = sprintf( '%d. %s', $tool_id, $tool['title'] );
			}

			$this->add_control(
				'tool_id',
				array(
					'label'   => esc_html__( 'انتخاب ابزار تعاملی', 'pixva' ),
					'type'    => \Elementor\Controls_Manager::SELECT2,
					'default' => '1',
					'options' => $options,
				)
			);

			$this->add_control(
				'layout',
				array(
					'label'   => esc_html__( 'حالت نمایش', 'pixva' ),
					'type'    => \Elementor\Controls_Manager::SELECT,
					'default' => 'section',
					'options' => array(
						'section' => esc_html__( 'سکشن کامل', 'pixva' ),
						'inline'  => esc_html__( 'فشرده / درون‌خطی', 'pixva' ),
					),
				)
			);

			$this->end_controls_section();
		}

		/**
		 * خروجی.
		 *
		 * @return void
		 */
		protected function render() {
			$settings = $this->get_settings_for_display();
			$tool_id  = isset( $settings['tool_id'] ) ? (int) $settings['tool_id'] : 1;
			$layout   = isset( $settings['layout'] ) && 'inline' === $settings['layout'] ? 'inline' : 'section';
			echo pixva_render_tool_by_id( $tool_id, $layout ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
		}
	}
